const CONST_DECL_RE =
  /^\s*(?:(?:private|public|internal|protected)\s+)?(?:const\s+)?val\s+([A-Za-z_][A-Za-z0-9_]*)\s*(?::\s*[^=]+)?=\s*(.+?)\s*$/;

function parseLiteral(rhs) {
  const s = rhs.match(/^"((?:[^"\\]|\\.)*)"$/);
  if (s) return { kind: 'string', value: s[1] };
  const n = rhs.match(/^(-?\d+)$/);
  if (n) return { kind: 'number', value: Number(n[1]) };
  return { kind: 'expr', value: rhs };
}

function scanKotlinFile(rel) {
  const text = readFileSync(join(ROOT, rel), 'utf8');
  const lines = text.split('\n');
  const consts = new Map();
  lines.forEach((raw, idx) => {
    const m = raw.match(CONST_DECL_RE);
    if (!m) return;
    if (consts.has(m[1])) return;
    consts.set(m[1], { ...parseLiteral(m[2]), line: idx + 1, name: m[1] });
  });

  const resolveArg = (token) => {
    const t = token.trim();
    const lit = parseLiteral(t);
    if (lit.kind !== 'expr') return { ...lit, resolvedFrom: null, raw: t };
    if (consts.has(t)) {
      const c = consts.get(t);
      return { ...c, resolvedFrom: c.name, raw: t };
    }
    return { kind: 'expr', value: t, resolvedFrom: null, raw: t };
  };

  const matchAllWithLine = (re) => {
    const out = [];
    for (const m of text.matchAll(re)) {
      out.push({ m, line: indexToLine(text, m.index) });
    }
    return out;
  };

  return {
    rel,
    text,
    consts,
    resolveArg,
    idConsts: [...consts.values()].filter((c) => /(NOTIFICATION_ID|NOTIFY_ID|NOTIF_ID)$/.test(c.name)),
    channelConsts: [...consts.values()].filter((c) => /CHANNEL_ID$/.test(c.name)),
    startForeground: matchAllWithLine(/startForeground\s*\(\s*([^,\n]+?)\s*[,)]/g),
    notifyCalls: matchAllWithLine(/\.notify\s*\(\s*([^,\n]+?)\s*,/g),
    notificationChannelCtor: matchAllWithLine(/NotificationChannel\s*\(\s*([^,\n]+?)\s*,/g),
    builderCtor: matchAllWithLine(/NotificationCompat\.Builder\s*\(\s*[^,\n]+?\s*,\s*([^,\n)]+?)\s*\)/g),
    deleteChannel: matchAllWithLine(/deleteNotificationChannel\s*\(\s*([^,\n)]+?)\s*\)/g),
    contentLiterals: matchAllWithLine(/\.setContent(Title|Text)\s*\(\s*"((?:[^"\\]|\\.)*)"\s*\)/g),
  };
}

