#!/usr/bin/env node
/**
 * verify-android-vpn-wiring.mjs
 *
 * 防漂移守卫：验证 Android VPN 插件的「权限声明 / 原生 handler / 通知身份」三处接线一致。
 *
 * 用法:
 *   node scripts/verify-android-vpn-wiring.mjs [rootDir] [--json]
 *
 * rootDir 默认为 process.cwd()，可指向另一棵 git worktree（例如修复前的 b2906465）。
 * 退出码: 0 = 全部通过（允许带 advisory 警告）；1 = 存在 FAIL；2 = 环境/用法错误。
 *
 * 判定口径（刻意不做任何“为通过而放宽”）:
 *
 * D1 权限面一致 + 生成物卫生
 *   expected = (guest-js/index.ts 的 invoke('plugin:vpnservice|<name>') ∪ build.rs 的 COMMANDS)
 *   即「webview 声明 + 实际调用」的命令闭包。src/mobile.rs 的 run_mobile_plugin 是
 *   Rust 侧直接 JNI 调用、绕开 webview ACL，因此**不**参与 D1 的授权面判定，
 *   只参与 D2.2 的「与 Kotlin 方法名逐字相等」判定。
 *   要求:
 *     D1.1 expected 中的每个 JS/Rust 调用命令都必须出现在 build.rs COMMANDS 里
 *     D1.2 COMMANDS 中的每个命令都必须在 permissions/autogenerated/commands/*.toml 的
 *          commands.allow 里出现
 *     D1.4 COMMANDS 中的每个命令都必须在 migrated.json 里有 vpnservice:allow-*
 *     D1.5 migrated.json 中的每个 vpnservice:allow-* 都必须在 expected 里
 *     D1.6 每个 toml 内部 allow 集合 == deny 集合，且 identifier 后缀能解码回 allow 命令名
 *     D1.7 migrated.json 合法 JSON 且 vpnservice 权限无重复
 *     D1.8 【FAIL】权限 toml 的命令名集合 必须 == build.rs COMMANDS（无孤儿、无缺失）
 *          —— 即「permissions/ 是生成器不动点」这一不变量。孤儿 toml 永不自愈：
 *          tauri-plugin 的 build 脚本 autogenerate_command_permissions 只增不删
 *          (build/mod.rs:115)，define_permissions 用 glob 读全部文件 (:120)，
 *          因此孤儿会每次构建都被带进 schema.json / reference.md。
 *     D1.9 【WARN】reference.md / schemas/schema.json 中出现的权限标识符集合
 *          必须与 toml 的 identifier 集合逐字一致（生成物陈旧检测）。
 *          「与真生成器逐字节一致」由隔离 crate 跑真生成器 + diff -r 证明，
 *          守卫内刻意不跑 cargo（保持零依赖、秒级、任意 worktree 可用）。
 *   注意: 修复前 b2906465 的三个权限面是「互相一致地都缺 4 个命令」，因此仅有
 *   「三面集合相等」无法复现缺陷；必须用 JS/Rust 实际调用面作为锚点。这是本脚本
 *   能抓住该 bug 的关键。
 *
 * D2 Kotlin handler 覆盖（两个来源的派发语义不同，必须分开判定）
 *   (a) JS 面 —— guest-js/index.ts 的 invoke('plugin:vpnservice|<name>'):
 *       Tauri 在 ACL 通过后做 heck::AsLowerCamelCase 转换再下发给 Kotlin
 *       (tauri-2.10.3/src/webview/mod.rs:1867-1870)。Kotlin 侧
 *       PluginHandle.indexMethods() 以「Kotlin 方法名」为 key 建表
 *       (mobile/android/.../PluginHandle.kt:144-157)，PluginHandle.invoke() 用
 *       commands[invoke.command] 精确查找 (:139-140)。因此 JS 面的
 *       <snake_case> 必须对应 Kotlin `fun <lowerCamelCase>()` 上的紧邻 @Command。
 *       → D2 (FAIL)
 *   (b) Rust 面 —— src/mobile.rs 的 run_mobile_plugin("<name>"):
 *       该路径**不做任何大小写转换**，命令名原样传给 PluginManager.runCommand
 *       (tauri-2.10.3/src/plugin/mobile.rs:317 的 run_mobile_plugin → :429 的
 *       android run_command，形参 command 被原样 new_string 后下发)。它绕开
 *       webview 的 ACL 闸门，直接进 Kotlin 的 PluginHandle.invoke()，所以名字必须
 *       与 Kotlin 方法名**逐字相等**（这里是 lowerCamelCase）。本仓库 mobile.rs
 *       写的是 snake_case，故这些 Rust 包装器在 Android 上必然抛
 *       InvalidCommandException，属既有死代码（不在本次三个目标 bug 的范围内）。
 *       → D2.2 (WARN，不判 FAIL；如 Lead 决定清理应另行派活)
 *   例外：registerListener 不需要 Kotlin 方法。原因链是（已按框架源码修正）：
 *   extend_api 对本插件返回 false（tauri-2.10.3/src/plugin.rs:285 的 Builder 默认
 *   invoke_handler = |_| false，本插件 init() 未设置 invoke_handler），于是走
 *   mobile 分支下发 Kotlin；它能命中是因为 PluginHandle.indexMethods() 会沿父类链
 *   索引（PluginHandle.kt:146-150），而基类 Plugin 有
 *   `@Command open fun registerListener`（Plugin.kt:176-177）。
 *
 * D3 通知身份唯一
 *   扫描 tauri-plugin-vpnservice/android/** 与 easytier-gui/src-tauri/gen/android/app/**
 *   的全部 *.kt:
 *     D3.1 通知 id 常量（*NOTIFICATION_ID / *NOTIFY_ID）与 startForeground(...) / .notify(...)
 *          的 id 实参只能是 1355
 *     D3.2 channel id 常量（*CHANNEL_ID，排除 *OLD*CHANNEL_ID 这种仅用于
 *          deleteNotificationChannel 的遗留清理）与 NotificationChannel(...) /
 *          NotificationCompat.Builder(ctx, channel) 的 channel 实参只能是 easytier_channel_v2
 *     D3.3 TauriVpnService.kt 不得含硬编码英文通知文案（setContentTitle/setContentText 字面量）
 *     D3.4 【WARN】Kotlin 中以字面量名义请求的字符串资源（resolveString/getIdentifier "string"）
 *          必须真实存在于**合并后的**资源表 —— 即 app 模块 res 或插件库模块
 *          tauri-plugin-vpnservice/android/res 下的各 strings.xml。Android 库模块资源会合并进
 *          app 资源表（Tauri 通过 cargo:android_library_path 把插件注册为 Gradle library module），
 *          所以只扫 app 模块会误报插件自有的字符串。缺失才会静默落到硬编码 fallback，本地化失效。
 *          资源 lookup 本身是运行时的，故只判 WARN。
 */

