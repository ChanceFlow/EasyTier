const indexToLine = (text, index) => text.slice(0, index).split('\n').length;

const findLineContaining = (text, needle) => {
  const lines = text.split('\n');
  for (let i = 0; i < lines.length; i += 1) {
    if (lines[i].includes(needle)) return i + 1;
  }
  return null;
};

const uniq = (arr) => [...new Set(arr)];
const sorted = (iterable) => [...iterable].sort();

const readRel = (relPath) => {
  const abs = join(ROOT, relPath);
  if (!existsSync(abs)) return { relPath, missing: true, text: '' };
  if (!statSync(abs).isFile()) return { relPath, missing: true, text: '' };
  return { relPath, missing: false, text: readFileSync(abs, 'utf8') };
};

/** snake_case → lowerCamelCase，等价于 heck::AsLowerCamelCase（本仓库命令名均为小写 snake）。 */
const lowerCamel = (name) =>
  name
    .split('_')
    .map((part, i) => (i === 0 ? part : part.charAt(0).toUpperCase() + part.slice(1)))
    .join('');

/** 把 capability 权限后缀（kebab 或 camelCase）解码回 build.rs 使用的原始命令名。 */
const decodePermissionSuffix = (suffix) =>
  suffix.includes('-') ? suffix.replace(/-/g, '_') : suffix;

const extractQuoted = (chunk) => [...chunk.matchAll(/"([^"]*)"/g)].map((m) => m[1]);

const walkKtFiles = (relDir) => {
  const absDir = join(ROOT, relDir);
  if (!existsSync(absDir)) return [];
  const out = [];
  const visit = (abs, rel) => {
    let entries;
    try {
      entries = readdirSync(abs);
    } catch {
      return; // unreadable directory: nothing to scan
    }
    for (const entry of entries) {
      const a = join(abs, entry);
      const r = `${rel}/${entry}`;
      // lstat, never stat: an Android build leaves dangling symlinks behind
      // (gen/android/app/src/main/jniLibs/<abi>/lib*.so -> the cargo target dir,
      // which may be gone). Following one throws ENOENT and would turn this
      // guard into a hard crash instead of a verdict.
      let st;
      try {
        st = lstatSync(a);
      } catch {
        continue; // vanished between readdir and lstat
      }
      if (st.isSymbolicLink()) {
        // Resolve it, but only if it actually points somewhere; a broken link
        // is skipped rather than fatal.
        try {
          st = statSync(a);
        } catch {
          continue;
        }
      }
      if (st.isDirectory()) visit(a, r);
      else if (entry.endsWith('.kt')) out.push(r);
    }
  };
  visit(absDir, relDir);
  return out.sort();
};

