function collectInvokedCommands() {
  const out = [];
  const mobile = readRel(F_MOBILE_RS);
  if (!mobile.missing) {
    for (const m of mobile.text.matchAll(/run_mobile_plugin\s*\(\s*"([^"]+)"/g)) {
      out.push({ name: m[1], source: F_MOBILE_RS, line: indexToLine(mobile.text, m.index) });
    }
  }
  const guest = readRel(F_GUEST_JS);
  if (!guest.missing) {
    for (const m of guest.text.matchAll(
      /invoke(?:\s*<[^<>]*>)?\s*\(\s*['"]plugin:vpnservice\|([^'"]+)['"]/g,
    )) {
      out.push({ name: m[1], source: F_GUEST_JS, line: indexToLine(guest.text, m.index) });
    }
  }
  return { invoked: out, mobileMissing: mobile.missing, guestMissing: guest.missing };
}

function parseKotlinHandlers(text) {
  const lines = text.split('\n');
  const handlers = new Map(); // lowerCamel name -> line
  const orphanAnnotations = [];
  lines.forEach((raw, idx) => {
    if (raw.trim() !== '@Command') return;
    let j = idx + 1;
    let guard = 0;
    while (j < lines.length && guard < 4) {
      const t = lines[j].trim();
      if (t === '' || t.startsWith('//') || t.startsWith('/*') || t.startsWith('*') || t.startsWith('@')) {
        j += 1;
        guard += 1;
        continue;
      }
      break;
    }
    const t = j < lines.length ? lines[j].trim() : '';
    const m = t.match(/fun\s+([A-Za-z_][A-Za-z0-9_]*)\s*\(/);
    if (m) handlers.set(m[1], { line: j + 1 });
    else orphanAnnotations.push({ line: idx + 1, nextLine: t });
  });
  const decls = new Map(); // fun name -> line
  lines.forEach((raw, idx) => {
    const m = raw.match(/\bfun\s+([A-Za-z_][A-Za-z0-9_]*)\s*\(/);
    if (m && !decls.has(m[1])) decls.set(m[1], idx + 1);
  });
  return { handlers, orphanAnnotations, decls };
}

