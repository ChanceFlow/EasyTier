function runD1() {
  const build = readRel(F_BUILD_RS);
  const buildCommands = build.missing ? null : parseBuildRsCommands(build.text);
  const tomls = parsePermissionTomls();
  const migrated = parseMigratedJson();

  const { invoked, mobileMissing, guestMissing } = collectInvokedCommands();

  if (build.missing) {
    addResult({
      code: 'D1',
      item: 'build.rs 可读',
      expectation: `${F_BUILD_RS} 存在且含 COMMANDS 数组`,
      actual: '文件不存在',
      verdict: 'FAIL',
      details: [{ file: F_BUILD_RS, line: null, note: '文件不存在' }],
    });
  } else if (!buildCommands) {
    addResult({
      code: 'D1',
      item: 'build.rs COMMANDS 可解析',
      expectation: 'const COMMANDS: &[&str] = &[ ... ]',
      actual: '未匹配到 COMMANDS 数组',
      verdict: 'FAIL',
      details: [{ file: F_BUILD_RS, line: null, note: 'COMMANDS 数组不可解析' }],
    });
  }
  if (mobileMissing) {
    addResult({
      code: 'D1',
      item: 'src/mobile.rs 可读',
      expectation: `${F_MOBILE_RS} 存在`,
      actual: '文件不存在',
      verdict: 'FAIL',
      details: [{ file: F_MOBILE_RS, line: null, note: '文件不存在' }],
    });
  }
  if (guestMissing) {
    addResult({
      code: 'D1',
      item: 'guest-js/index.ts 可读',
      expectation: `${F_GUEST_JS} 存在`,
      actual: '文件不存在',
      verdict: 'FAIL',
      details: [{ file: F_GUEST_JS, line: null, note: '文件不存在' }],
    });
  }
  if (tomls.error) {
    addResult({
      code: 'D1',
      item: '权限 toml 目录可读',
      expectation: `${D_TOML}/*.toml 存在`,
      actual: tomls.error,
      verdict: 'FAIL',
      details: [],
    });
  }
  if (migrated.error) {
    addResult({
      code: 'D1',
      item: 'migrated.json 可读且合法',
      expectation: `${F_MIGRATED} 为合法 JSON 且含 permissions 数组`,
      actual: migrated.error,
      verdict: 'FAIL',
      details: [{ file: F_MIGRATED, line: null, note: migrated.error }],
    });
  }

  if (tomls.error || migrated.error || build.missing || !buildCommands) return;

  const declaredList = buildCommands;
  const declaredSet = new Set(declaredList.map((c) => c.name));

  // ACL 只约束 webview 调用面（guest-js 的 plugin:vpnservice|<name>）。
  // src/mobile.rs 的 run_mobile_plugin 是 Rust 侧直接 JNI 调用，绕过 webview ACL
  // (tauri/src/plugin/mobile.rs:429 起直接调 PluginManager.runCommand)，因此它的命令名
  // 不需要 COMMANDS/权限授权 —— 它只需与 Kotlin 方法名逐字相等（见 D2.2）。
  const webviewInvoked = invoked.filter((c) => c.source === F_GUEST_JS);
  const invokedSet = new Set(webviewInvoked.map((c) => c.name));
  const expectedSet = new Set([...invokedSet, ...declaredSet]);

  const tomlAllowList = tomls.files.flatMap((f) => f.allow.map((a) => ({ ...a, file: f.rel })));
  const tomlAllowSet = new Set(tomlAllowList.map((a) => a.name));
  const migratedAllowList = migrated.entries.filter((e) => e.kind === 'allow');
  const migratedAllowSet = new Set(migratedAllowList.map((e) => e.name));

  // D1.1 webview 实际调用面 ⊆ COMMANDS
  const missingFromBuild = [...invokedSet].filter((n) => !declaredSet.has(n));
  {
    const details = [];
    for (const n of sorted(missingFromBuild)) {
      for (const occ of webviewInvoked.filter((c) => c.name === n)) {
        details.push({
          file: occ.source,
          line: occ.line,
          note: `webview 实际调用 "${n}"，但 ${F_BUILD_RS} 的 COMMANDS 未声明（该 invoke 会被 ACL 拒绝）`,
        });
      }
    }
    addResult({
      code: 'D1',
      item: 'D1.1 webview 调用命令 (plugin:vpnservice|<name>) ⊆ build.rs COMMANDS',
      expectation: `${sorted(invokedSet).length} 个 webview 实际调用命令全部出现在 COMMANDS`,
      actual:
        missingFromBuild.length === 0
          ? '无缺失'
          : `COMMANDS 缺 ${missingFromBuild.length} 个: ${sorted(missingFromBuild).join(', ')}`,
      verdict: missingFromBuild.length === 0 ? 'PASS' : 'FAIL',
      details,
    });
  }

  // D1.2 COMMANDS ⊆ toml allow
  const missingInToml = [...declaredSet].filter((n) => !tomlAllowSet.has(n));
  addResult({
    code: 'D1',
    item: 'D1.2 build.rs COMMANDS ⊆ 权限 toml commands.allow',
    expectation: `${declaredSet.size} 个 COMMANDS 全部有对应 toml`,
    actual:
      missingInToml.length === 0
        ? '无缺失'
        : `toml 缺 ${missingInToml.length} 个: ${sorted(missingInToml).join(', ')}`,
    verdict: missingInToml.length === 0 ? 'PASS' : 'FAIL',
    details: sorted(missingInToml).map((n) => ({
      file: `${D_TOML}/<missing>.toml`,
      line: null,
      note: `COMMANDS 声明 "${n}"，但 ${D_TOML} 下没有任何 toml 的 commands.allow 包含它`,
    })),
  });

  // D1.8 权限 toml 无孤儿（toml ⊆ COMMANDS）—— 生成器不动点不变量
  const orphanToml = [...tomlAllowSet].filter((n) => !declaredSet.has(n));
  addResult({
    code: 'D1',
    item: 'D1.8 build.rs COMMANDS ↔ 权限 toml 无孤儿',
    expectation:
      'toml 的命令名集合必须 ⊆ COMMANDS（反向包含由 D1.2 断言）；否则孤儿 toml 永不自愈，' +
      '会被 autogenerate_command_permissions(只增不删) + define_permissions(glob 读全部) 永久带进 schema.json/reference.md',
    actual:
      orphanToml.length === 0
        ? `${tomlAllowSet.size} 个 toml 命令全部在 COMMANDS 中，无孤儿`
        : `发现 ${orphanToml.length} 个孤儿 toml 命令: ${sorted(orphanToml).join(', ')}`,
    verdict: orphanToml.length === 0 ? 'PASS' : 'FAIL',
    details: sorted(orphanToml).map((n) => {
      const hit = tomlAllowList.find((a) => a.name === n);
      return {
        file: hit?.file ?? D_TOML,
        line: hit?.line ?? null,
        note: `孤儿权限：toml 声明命令 "${n}"，但 ${F_BUILD_RS} 的 COMMANDS 里没有它（生成器不会删除该文件）`,
      };
    }),
  });

  // D1.9 生成物 reference.md / schema.json 与 toml identifier 集合一致（WARN 级）
  {
    const tomlIds = new Set(tomls.files.flatMap((f) => f.identifiers.map((i) => i.id)));
    const checkGenerated = (relPath, label) => {
      const { missing, text } = readRel(relPath);
      if (missing) {
        addResult({
          code: 'D1',
          item: `D1.9 生成物集合一致 — ${label}`,
          expectation: `${relPath} 存在且其权限标识符集合 == toml 的 identifier 集合`,
          actual: '文件不存在',
          verdict: 'WARN',
          details: [{ file: relPath, line: null, note: '生成物文件缺失' }],
        });
        return;
      }
      const actualIds = extractPermissionIds(text);
      const onlyInGen = [...actualIds].filter((i) => !tomlIds.has(i));
      const onlyInToml = [...tomlIds].filter((i) => !actualIds.has(i));
      addResult({
        code: 'D1',
        item: `D1.9 生成物集合一致 — ${label}`,
        expectation: `${relPath} 的权限标识符集合 == toml identifier 集合 (${tomlIds.size} 个)`,
        actual:
          onlyInGen.length === 0 && onlyInToml.length === 0
            ? `一致（${actualIds.size} 个标识符）`
            : `陈旧/漂移：生成物多 ${onlyInGen.length} 个 [${onlyInGen.join(', ')}]，少 ${onlyInToml.length} 个 [${onlyInToml.join(', ')}]`,
        verdict: onlyInGen.length === 0 && onlyInToml.length === 0 ? 'PASS' : 'WARN',
        details: [
          ...onlyInGen.map((i) => ({
            file: relPath,
            line: findLineContaining(text, i),
            note: `生成物含 toml 中不存在的 identifier "${i}"`,
          })),
          ...onlyInToml.map((i) => ({
            file: relPath,
            line: null,
            note: `toml 有 identifier "${i}"，但生成物未收录（生成物陈旧，需用真生成器重算）`,
          })),
        ],
      });
    };
    checkGenerated(F_REFERENCE_MD, 'reference.md');
    checkGenerated(F_SCHEMA_JSON, 'schema.json');
  }

  // D1.4 COMMANDS ⊆ migrated allow
  const missingInMigrated = [...declaredSet].filter((n) => !migratedAllowSet.has(n));
  addResult({
    code: 'D1',
    item: 'D1.4 build.rs COMMANDS ⊆ migrated.json vpnservice:allow-*',
    expectation: `${declaredSet.size} 个 COMMANDS 全部有对应 capability 授权`,
    actual:
      missingInMigrated.length === 0
        ? '无缺失'
        : `migrated.json 缺 ${missingInMigrated.length} 个: ${sorted(missingInMigrated).join(', ')}`,
    verdict: missingInMigrated.length === 0 ? 'PASS' : 'FAIL',
    details: sorted(missingInMigrated).map((n) => {
      const kebab = n.replace(/_/g, '-');
      const candidates = [
        `vpnservice:allow-${kebab}`,
        `vpnservice:allow-${lowerCamel(n)}`,
        `vpnservice:allow-${n}`,
      ];
      const known = migratedAllowList.find((e) => e.name === n);
      return {
        file: F_MIGRATED,
        line: known ? known.line : findLineContaining(migrated.entries.length ? readRel(F_MIGRATED).text : '', candidates[0]),
        note: `COMMANDS 声明 "${n}"，但 migrated.json 的 permissions 里没有 ${candidates.map((c) => `"${c}"`).join(' / ')}`,
      };
    }),
  });

  // D1.5 migrated allow ⊆ expected
  const extraInMigrated = [...migratedAllowSet].filter((n) => !expectedSet.has(n));
  addResult({
    code: 'D1',
    item: 'D1.5 migrated.json vpnservice:allow-* ⊆ 期望命令集',
    expectation: 'capability 中不出现期望集合之外的授权',
    actual:
      extraInMigrated.length === 0
        ? '无多余项'
        : `多余 ${extraInMigrated.length} 个: ${sorted(extraInMigrated).join(', ')}`,
    verdict: extraInMigrated.length === 0 ? 'PASS' : 'FAIL',
    details: extraInMigrated.map((n) => ({
      file: F_MIGRATED,
      line: migratedAllowList.find((e) => e.name === n)?.line ?? null,
      note: `capability 授权了期望集合外的命令 "${n}"`,
    })),
  });

  // D1.6 toml 内部一致性
  {
    const problems = [];
    for (const f of tomls.files) {
      const allowNames = uniq(f.allow.map((a) => a.name));
      const denyNames = uniq(f.deny.map((d) => d.name));
      const missingDeny = allowNames.filter((n) => !denyNames.includes(n));
      const missingAllow = denyNames.filter((n) => !allowNames.includes(n));
      if (missingDeny.length || missingAllow.length) {
        problems.push({
          file: f.rel,
          line: f.allow[0]?.line ?? f.deny[0]?.line ?? null,
          note: `allow/deny 不对称: allow-only=[${missingDeny.join(',')}] deny-only=[${missingAllow.join(',')}]`,
        });
      }
      for (const ident of f.identifiers) {
        const m = ident.id.match(/^(allow|deny)-(.+)$/);
        if (!m) {
          problems.push({ file: f.rel, line: ident.line, note: `identifier "${ident.id}" 前缀不是 allow-/deny-` });
          continue;
        }
        const decoded = decodePermissionSuffix(m[2]);
        const expectedName = m[1] === 'allow' ? allowNames : denyNames;
        if (expectedName.length && !expectedName.includes(decoded)) {
          problems.push({
            file: f.rel,
            line: ident.line,
            note: `identifier "${ident.id}" 解码为 "${decoded}"，与 commands.${m[1]} = [${expectedName.join(', ')}] 不一致`,
          });
        }
      }
    }
    addResult({
      code: 'D1',
      item: 'D1.6 toml 内部一致 (allow==deny, identifier↔commands 可解码)',
      expectation: '每个 toml 的 allow/deny 对称，且 identifier 后缀可解码回命令名',
      actual: problems.length === 0 ? `${tomls.files.length} 个 toml 全部一致` : `${problems.length} 处不一致`,
      verdict: problems.length === 0 ? 'PASS' : 'FAIL',
      details: problems,
    });
  }

  // D1.7 migrated.json vpnservice 权限无重复、无异常形式
  {
    const problems = [];
    const seen = new Map();
    for (const e of migrated.entries) {
      if (seen.has(e.raw)) {
        problems.push({ file: F_MIGRATED, line: e.line, note: `重复条目 "${e.raw}"` });
      }
      seen.set(e.raw, e);
      if (!e.kind) {
        problems.push({
          file: F_MIGRATED,
          line: e.line,
          note: `"${e.raw}" 不是 allow-/deny- 形式，无法映射到命令名`,
        });
      }
    }
    addResult({
      code: 'D1',
      item: 'D1.7 migrated.json vpnservice 权限形式与去重',
      expectation: '每条 vpnservice: 权限都是 allow-/deny- 形式且不重复',
      actual:
        problems.length === 0
          ? `${migrated.entries.length} 条 vpnservice 权限形式正确且无重复`
          : `${problems.length} 处问题`,
      verdict: problems.length === 0 ? 'PASS' : 'FAIL',
      details: problems,
    });
  }

  // 期望集合与三面集合概览（信息性）
  addResult({
    code: 'D1',
    item: 'D1.0 集合概览',
    expectation: 'expected = (guest-js webview 调用面) ∪ COMMANDS',
    actual:
      `expected(${expectedSet.size}) = [${sorted(expectedSet).join(', ')}] | ` +
      `COMMANDS(${declaredSet.size}) = [${sorted(declaredSet).join(', ')}] | ` +
      `toml(${tomlAllowSet.size}) = [${sorted(tomlAllowSet).join(', ')}] | ` +
      `migrated(${migratedAllowSet.size}) = [${sorted(migratedAllowSet).join(', ')}]`,
    verdict: 'INFO',
    details: [],
  });
}

