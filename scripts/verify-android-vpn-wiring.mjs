function runD2() {
  const { invoked, mobileMissing, guestMissing } = collectInvokedCommands();
  const kt = readRel(F_PLUGIN_KT);

  if (mobileMissing || guestMissing) {
    addResult({
      code: 'D2',
      item: 'D2 输入面可读',
      expectation: `${F_MOBILE_RS} 与 ${F_GUEST_JS} 都可读`,
      actual: `mobile.rs=${mobileMissing ? 'MISSING' : 'ok'}, guest-js=${guestMissing ? 'MISSING' : 'ok'}`,
      verdict: 'FAIL',
      details: [],
    });
    return;
  }
  if (kt.missing) {
    addResult({
      code: 'D2',
      item: 'D2 VpnServicePlugin.kt 可读',
      expectation: `${F_PLUGIN_KT} 存在`,
      actual: '文件不存在',
      verdict: 'FAIL',
      details: [{ file: F_PLUGIN_KT, line: null, note: '文件不存在' }],
    });
    return;
  }

  const { handlers, orphanAnnotations, decls } = parseKotlinHandlers(kt.text);

  // 两个来源的派发语义不同（见文件头 D2 说明），必须分开判定。
  const guestNames = uniq(invoked.filter((c) => c.source === F_GUEST_JS).map((c) => c.name));
  const mobileNames = uniq(invoked.filter((c) => c.source === F_MOBILE_RS).map((c) => c.name));
  const requiredJs = guestNames.filter((n) => !CORE_HANDLED_COMMANDS.has(n));
  const skipped = guestNames.filter((n) => CORE_HANDLED_COMMANDS.has(n));

  // --- D2 (FAIL): JS 面 snake_case → lowerCamelCase → 紧邻 @Command -----------------
  const details = [];
  for (const name of sorted(requiredJs)) {
    const camel = lowerCamel(name);
    if (handlers.has(camel)) continue;
    const declLine = decls.get(camel);
    if (declLine) {
      details.push({
        file: F_PLUGIN_KT,
        line: declLine,
        note: `fun ${camel}(...) 存在，但上方没有 @Command 注解（JS 命令 "${name}" 不会被注册）`,
      });
    } else {
      const occ = invoked.find((c) => c.name === name && c.source === F_GUEST_JS);
      details.push({
        file: F_PLUGIN_KT,
        line: null,
        note: `JS 命令 "${name}" (期望 fun ${camel}) 在 ${F_PLUGIN_KT} 中完全没有对应方法；调用点 ${occ?.source}:${occ?.line}`,
      });
    }
  }

  addResult({
    code: 'D2',
    item: 'D2 JS 面 (plugin:vpnservice|<name>) 每个命令都有紧邻 @Command 的 Kotlin 方法',
    expectation: `${requiredJs.length} 个 JS 命令 (heck::AsLowerCamelCase) 均有 @Command fun`,
    actual:
      details.length === 0
        ? `全部覆盖: ${sorted(requiredJs).join(', ')}`
        : `缺 ${details.length} 个: ${details.map((d) => d.note).join(' | ')}`,
    verdict: details.length === 0 ? 'PASS' : 'FAIL',
    details,
  });

  addResult({
    code: 'D2',
    item: 'D2.1 @Command 紧邻性',
    expectation: '@Command 与下一个方法声明之间只有空行/注释/其它注解',
    actual:
      orphanAnnotations.length === 0
        ? '未发现悬空 @Command'
        : `${orphanAnnotations.length} 个 @Command 未紧邻方法声明`,
    verdict: orphanAnnotations.length === 0 ? 'PASS' : 'FAIL',
    details: orphanAnnotations.map((o) => ({
      file: F_PLUGIN_KT,
      line: o.line,
      note: `@Command 之后的首个代码行不是 fun 声明: "${o.nextLine}"`,
    })),
  });

  // --- D2.2 (WARN): Rust 面 run_mobile_plugin 原样下发，名字须与 Kotlin 方法名逐字相等 ---
  {
    const mismatches = mobileNames.filter((n) => !handlers.has(n));
    addResult({
      code: 'D2',
      item: 'D2.2 Rust 面 (run_mobile_plugin) 命令名与 Kotlin @Command 方法名逐字相等',
      expectation:
        'run_mobile_plugin 不做大小写转换（plugin/mobile.rs:317→:429 原样下发），故其名字必须逐字等于 Kotlin 方法名；' +
        'snake_case 名字永远命中不了 lowerCamelCase 方法，属既有死代码',
      actual:
        mismatches.length === 0
          ? `${mobileNames.length} 个 Rust 包装器均可命中 Kotlin @Command`
          : `${mismatches.length}/${mobileNames.length} 个 Rust 包装器无法命中（既有死代码，非本次三个目标 bug）: ${sorted(mismatches).join(', ')}`,
      verdict: mismatches.length === 0 ? 'PASS' : 'WARN',
      details: sorted(mismatches).map((n) => {
        const occ = invoked.find((c) => c.name === n && c.source === F_MOBILE_RS);
        return {
          file: F_MOBILE_RS,
          line: occ?.line ?? null,
          note: `run_mobile_plugin("${n}") 原样下发，Kotlin 侧无同名方法（存在的是 fun ${lowerCamel(n)}），该包装器在 Android 上必然 InvalidCommandException`,
        };
      }),
    });
  }

  addResult({
    code: 'D2',
    item: 'D2.0 覆盖概览',
    expectation: '信息性：两个调用面的命令 vs Kotlin @Command 名称',
    actual:
      `JS 面(${guestNames.length}) = [${sorted(guestNames).join(', ')}] | ` +
      `Rust 面(${mobileNames.length}) = [${sorted(mobileNames).join(', ')}] | ` +
      `Kotlin @Command(${handlers.size}) = [${sorted(handlers.keys()).join(', ')}] | ` +
      `核心处理已排除 = [${sorted(skipped).join(', ') || '无'}]`,
    verdict: 'INFO',
    details: [],
  });
}

