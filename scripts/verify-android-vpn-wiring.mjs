/**
 * registerListener 不应有 Kotlin 方法。原因链（依框架源码）：
 *   extend_api 对本插件返回 false —— Builder 默认 invoke_handler = |_| false
 *   (tauri-2.10.3/src/plugin.rs:285)，本插件 init() 未设置 invoke_handler；
 *   于是 mobile 分支把命令下发给 Kotlin；能命中是因为
 *   PluginHandle.indexMethods() 沿父类链索引 (PluginHandle.kt:146-150)，
 *   而基类 Plugin 有 `@Command open fun registerListener` (Plugin.kt:176-177)。
 *   注意：**不是**因为「Tauri 核心 extend_api 替我们处理了」——它恰恰返回 false。
 */
