function parseBuildRsCommands(text) {
  const m = text.match(/COMMANDS\s*:\s*&\[&str\]\s*=\s*&\[([\s\S]*?)\]/);
  if (!m) return null;
  const body = m[1];
  const base = m.index + m[0].indexOf(body);
  return [...body.matchAll(/"([^"]+)"/g)].map((q) => ({
    name: q[1],
    line: indexToLine(text, base + q.index),
  }));
}

function parsePermissionTomls() {
  const absDir = join(ROOT, D_TOML);
  if (!existsSync(absDir)) return { error: `目录不存在或不可读: ${D_TOML}`, files: [] };
  const files = readdirSync(absDir).filter((f) => f.endsWith('.toml')).sort();
  const parsed = files.map((f) => {
    const rel = `${D_TOML}/${f}`;
    const text = readFileSync(join(absDir, f), 'utf8');
    const blockValues = (key) => {
      const re = new RegExp(`${key.replace(/\./g, '\\.')}\\s*=\\s*\\[([^\\]]*)\\]`, 'g');
      const values = [];
      for (const m of text.matchAll(re)) {
        const chunk = m[1];
        const base = m.index + m[0].indexOf('[') + 1;
        for (const q of chunk.matchAll(/"([^"]+)"/g)) {
          values.push({ name: q[1], line: indexToLine(text, base + q.index) });
        }
      }
      return values;
    };
    return {
      rel,
      identifiers: [...text.matchAll(/identifier\s*=\s*"([^"]+)"/g)].map((m) => ({
        id: m[1],
        line: indexToLine(text, m.index),
      })),
      allow: blockValues('commands.allow'),
      deny: blockValues('commands.deny'),
    };
  });
  return { files: parsed };
}

function parseMigratedJson() {
  const { relPath, missing, text } = readRel(F_MIGRATED);
  if (missing) return { error: `文件不存在: ${F_MIGRATED}`, entries: [] };
  let json;
  try {
    json = JSON.parse(text);
  } catch (e) {
    return { error: `JSON 解析失败: ${e.message}`, entries: [] };
  }
  if (!Array.isArray(json.permissions)) {
    return { error: 'permissions 数组不存在', entries: [] };
  }
  const entries = [];
  for (const [i, p] of json.permissions.entries()) {
    if (typeof p !== 'string' || !p.startsWith('vpnservice:')) continue;
    const suffix = p.slice('vpnservice:'.length);
    const m = suffix.match(/^(allow|deny)-(.+)$/);
    entries.push({
      raw: p,
      index: i,
      kind: m ? m[1] : null,
      name: m ? decodePermissionSuffix(m[2]) : null,
      line: findLineContaining(text, `"${p}"`),
    });
  }
  return { entries };
}

