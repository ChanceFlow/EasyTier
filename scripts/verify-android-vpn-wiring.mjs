function runD3() {
  const files = D3_SCOPE_DIRS.flatMap((d) => walkKtFiles(d));
  if (files.length === 0) {
    addResult({
      code: 'D3',
      item: 'D3 扫描范围',
      expectation: `${D3_SCOPE_DIRS.join(' , ')} 下存在 *.kt`,
      actual: '未找到任何 .kt 文件',
      verdict: 'FAIL',
      details: D3_SCOPE_DIRS.map((d) => ({ file: d, line: null, note: '目录不存在或没有 .kt' })),
    });
    return;
  }

  const scanned = files.map(scanKotlinFile);

  // D3.1 通知 id
  {
    const problems = [];
    for (const f of scanned) {
      for (const c of f.idConsts) {
        if (c.kind !== 'number') {
          problems.push({
            file: f.rel,
            line: c.line,
            note: `常量 ${c.name} 不是数字字面量 (${JSON.stringify(c.value)})，无法静态确认等于 ${EXPECTED_NOTIFICATION_ID}`,
          });
          continue;
        }
        if (c.value !== EXPECTED_NOTIFICATION_ID) {
          problems.push({
            file: f.rel,
            line: c.line,
            note: `常量 ${c.name} = ${c.value}，期望 ${EXPECTED_NOTIFICATION_ID}`,
          });
        }
      }
      const callSites = [
        ...f.startForeground.map((x) => ({ ...x, what: 'startForeground' })),
        ...f.notifyCalls.map((x) => ({ ...x, what: 'notify' })),
      ];
      for (const site of callSites) {
        const resolved = f.resolveArg(site.m[1]);
        if (resolved.kind === 'number') {
          if (resolved.value !== EXPECTED_NOTIFICATION_ID) {
            problems.push({
              file: f.rel,
              line: site.line,
              note: `${site.what}(${resolved.raw}${resolved.resolvedFrom ? ` = ${resolved.value}` : ''}, ...) 通知 id = ${resolved.value}，期望 ${EXPECTED_NOTIFICATION_ID}`,
            });
          }
        } else if (resolved.kind === 'expr') {
          problems.push({
            file: f.rel,
            line: site.line,
            note: `${site.what}(${resolved.raw}, ...) 的 id 实参无法静态解析 (${resolved.value})`,
          });
        }
      }
    }
    addResult({
      code: 'D3',
      item: 'D3.1 VPN 常驻通知 id 唯一 = 1355',
      expectation: `所有通知 id 常量与 startForeground/notify 的 id 实参都等于 ${EXPECTED_NOTIFICATION_ID}`,
      actual: problems.length === 0 ? '全部为 1355' : `${problems.length} 处非 ${EXPECTED_NOTIFICATION_ID}`,
      verdict: problems.length === 0 ? 'PASS' : 'FAIL',
      details: problems,
    });
  }

  // D3.2 channel id
  {
    const problems = [];
    const tolerated = [];
    for (const f of scanned) {
      for (const c of f.channelConsts) {
        if (/OLD/i.test(c.name)) {
          tolerated.push({
            file: f.rel,
            line: c.line,
            note: `遗留 channel 常量 ${c.name} = ${JSON.stringify(c.value)}（仅用于 deleteNotificationChannel 清理，TOLERATED）`,
          });
          continue;
        }
        if (c.kind !== 'string') {
          problems.push({
            file: f.rel,
            line: c.line,
            note: `常量 ${c.name} 不是字符串字面量，无法静态确认等于 "${EXPECTED_CHANNEL_ID}"`,
          });
          continue;
        }
        if (c.value !== EXPECTED_CHANNEL_ID) {
          problems.push({
            file: f.rel,
            line: c.line,
            note: `常量 ${c.name} = "${c.value}"，期望 "${EXPECTED_CHANNEL_ID}"`,
          });
        }
      }
      const channelSites = [
        ...f.notificationChannelCtor.map((x) => ({ ...x, what: 'NotificationChannel' })),
        ...f.builderCtor.map((x) => ({ ...x, what: 'NotificationCompat.Builder' })),
      ];
      for (const site of channelSites) {
        const resolved = f.resolveArg(site.m[1]);
        if (resolved.kind === 'string') {
          if (resolved.value !== EXPECTED_CHANNEL_ID) {
            problems.push({
              file: f.rel,
              line: site.line,
              note: `${site.what}(..., "${resolved.value}"${resolved.resolvedFrom ? ` via ${resolved.resolvedFrom}` : ''}, ...) channel id 非 "${EXPECTED_CHANNEL_ID}"`,
            });
          }
        } else if (resolved.kind === 'expr') {
          problems.push({
            file: f.rel,
            line: site.line,
            note: `${site.what} 的 channel 实参无法静态解析 (${resolved.value})`,
          });
        }
      }
      for (const site of f.deleteChannel) {
        const resolved = f.resolveArg(site.m[1]);
        if (resolved.kind === 'string' && resolved.value !== EXPECTED_CHANNEL_ID) {
          tolerated.push({
            file: f.rel,
            line: site.line,
            note: `deleteNotificationChannel("${resolved.value}") —— 遗留 channel 清理，TOLERATED`,
          });
        }
      }
    }
    addResult({
      code: 'D3',
      item: 'D3.2 VPN 通知 channel id 唯一 = easytier_channel_v2',
      expectation: `所有在建/发通知路径上使用的 channel id 都等于 "${EXPECTED_CHANNEL_ID}"`,
      actual: problems.length === 0 ? `全部为 "${EXPECTED_CHANNEL_ID}"` : `${problems.length} 处非 "${EXPECTED_CHANNEL_ID}"`,
      verdict: problems.length === 0 ? 'PASS' : 'FAIL',
      details: problems,
    });
    if (tolerated.length) {
      addResult({
        code: 'D3',
        item: 'D3.2a 遗留 channel 清理（仅提示）',
        expectation: 'deleteNotificationChannel 允许引用历史 channel id',
        actual: `${tolerated.length} 处遗留引用（不计为失败）`,
        verdict: 'WARN',
        details: tolerated,
      });
    }
  }

  // D3.3 硬编码英文通知文案
  {
    const tvs = scanned.find((f) => f.rel === F_TAURI_VPN_SERVICE_KT);
    if (!tvs) {
      addResult({
        code: 'D3',
        item: 'D3.3 TauriVpnService.kt 可读',
        expectation: `${F_TAURI_VPN_SERVICE_KT} 存在`,
        actual: '文件不存在',
        verdict: 'FAIL',
        details: [{ file: F_TAURI_VPN_SERVICE_KT, line: null, note: '文件不存在' }],
      });
    } else {
      const english = [];
      const otherLiterals = [];
      for (const hit of tvs.contentLiterals) {
        const which = hit.m[1];
        const value = hit.m[2];
        const isAscii = /^[\x00-\x7F]*$/.test(value) && /[A-Za-z]/.test(value);
        if (isAscii) {
          english.push({
            file: tvs.rel,
            line: hit.line,
            note: `setContent${which}("${value}") —— 硬编码英文通知文案，应改为本地化字符串（R.string / resources.getIdentifier）`,
          });
        } else {
          otherLiterals.push({
            file: tvs.rel,
            line: hit.line,
            note: `setContent${which}("${value}") —— 仍是硬编码字面量（非英文，未计为失败）`,
          });
        }
      }
      addResult({
        code: 'D3',
        item: 'D3.3 TauriVpnService.kt 无硬编码英文通知标题/正文',
        expectation: 'setContentTitle/setContentText 只接受本地化字符串，不接受英文字面量',
        actual: english.length === 0 ? '未发现硬编码英文字面量' : `${english.length} 处硬编码英文`,
        verdict: english.length === 0 ? 'PASS' : 'FAIL',
        details: english,
      });
      if (otherLiterals.length) {
        addResult({
          code: 'D3',
          item: 'D3.3a 其它硬编码通知字面量（仅提示）',
          expectation: '通知文案应全部本地化',
          actual: `${otherLiterals.length} 处硬编码字面量（不计为失败）`,
          verdict: 'WARN',
          details: otherLiterals,
        });
      }
    }
  }

  // D3.4 （WARN）Kotlin 中以字面量名义请求的字符串资源必须真实存在
  {
    // Android library-module resources are merged into the consuming app's
    // resource table, so a runtime getIdentifier()/getString() resolved against
    // the app package legitimately finds names declared in the plugin's own
    // res/ too. That is how this plugin ships its copy: tauri-plugin's build
    // script registers tauri-plugin-vpnservice/android through
    // cargo:android_library_path, and the Android integration adds it as a
    // Gradle library module. Scanning only the app module would therefore
    // report false positives for every plugin-owned string.
    const resRoots = [
      'easytier-gui/src-tauri/gen/android',
      'tauri-plugin-vpnservice/android',
    ];
    const resFiles = [];
    const collect = (rel) => {
      const abs = join(ROOT, rel);
      if (!existsSync(abs)) return;
      if (statSync(abs).isDirectory()) {
        for (const e of readdirSync(abs)) collect(`${rel}/${e}`);
      } else if (rel.endsWith('strings.xml')) {
        resFiles.push(rel);
      }
    };
    for (const resRoot of resRoots) collect(resRoot);
    const defined = new Set();
    for (const r of resFiles) {
      for (const m of readFileSync(join(ROOT, r), 'utf8').matchAll(/<string\s+name="([^"]+)"/g)) {
        defined.add(m[1]);
      }
    }
    const wants = [];
    for (const f of scanned) {
      for (const m of f.text.matchAll(/resolveString\s*\(([^)]*)\)/g)) {
        const name = [...m[1].matchAll(/"([^"]*)"/g)]
          .map((x) => x[1])
          .find((v) => /^[a-z][a-z0-9_]*$/.test(v));
        if (name) wants.push({ name, file: f.rel, line: indexToLine(f.text, m.index) });
      }
      for (const m of f.text.matchAll(/getIdentifier\s*\(\s*"([A-Za-z0-9_]+)"\s*,\s*"string"/g)) {
        wants.push({ name: m[1], file: f.rel, line: indexToLine(f.text, m.index) });
      }
    }
    const seen = new Map();
    for (const w of wants) {
      if (!seen.has(w.name)) seen.set(w.name, []);
      seen.get(w.name).push(w);
    }
    const missing = [...seen.entries()].filter(([name]) => !defined.has(name));
    addResult({
      code: 'D3',
      item: 'D3.4 Kotlin 请求的字符串资源存在于合并后的资源表（app + 插件库模块，WARN 级）',
      expectation:
        `${resFiles.length} 个 strings.xml 中定义了 resolveString/getIdentifier 字面量请求的全部资源名` +
        '（库模块资源会合并进 app 资源表；缺失才会静默落到硬编码 fallback，本地化失效）',
      actual:
        missing.length === 0
          ? `全部存在（${seen.size} 个资源名）`
          : `${missing.length} 个资源名缺失，将静默使用 fallback: ${missing.map(([n]) => n).join(', ')}`,
      verdict: missing.length === 0 ? 'PASS' : 'WARN',
      details: missing.flatMap(([name, sites]) =>
        sites.map((s) => ({
          file: s.file,
          line: s.line,
          note: `请求字符串资源 "${name}"，但 ${resFiles.join(' / ')} 中均未定义`,
        })),
      ),
    });
  }

  addResult({
    code: 'D3',
    item: 'D3.0 扫描范围',
    expectation: `${D3_SCOPE_DIRS.join(' , ')} 下全部 *.kt`,
    actual: `${files.length} 个文件: ${files.join(', ')}`,
    verdict: 'INFO',
    details: [],
  });
}

// ===========================================================================
// 主流程 + 输出
// ===========================================================================

function finish() {
  const failures = results.filter((r) => r.verdict === 'FAIL');
  const warnings = results.filter((r) => r.verdict === 'WARN');
  const heading = `android-vpn-wiring guard — root=${ROOT}`;

  if (jsonMode) {
    console.log(
      JSON.stringify(
        {
          root: ROOT,
          exitCode: failures.length ? 1 : 0,
          summary: {
            total: results.length,
            fail: failures.length,
            warn: warnings.length,
            pass: results.filter((r) => r.verdict === 'PASS').length,
          },
          failures: failures.map((f) => ({
            code: f.code,
            item: f.item,
            expectation: f.expectation,
            actual: f.actual,
            locations: f.details.map((d) => (d.line ? `${d.file}:${d.line}` : d.file)).filter(Boolean),
            notes: f.details.map((d) => d.note),
          })),
          results,
        },
        null,
        2,
      ),
    );
  } else {
    console.log(heading);
    console.log('='.repeat(heading.length));
    for (const r of results) {
      console.log('');
      console.log(`[${r.code}] 检查项: ${r.item}`);
      console.log(`  期望: ${r.expectation}`);
      console.log(`  实际: ${r.actual}`);
      console.log(`  结论: ${r.verdict}`);
      for (const d of r.details) {
        console.log(`    - ${d.line ? `${d.file}:${d.line}` : d.file}  ${d.note}`);
      }
    }

    console.log('');
    console.log('-'.repeat(heading.length));
    if (failures.length === 0) {
      console.log(`RESULT: PASS (${warnings.length} warning(s))`);
    } else {
      console.log(`RESULT: FAIL — ${failures.length} failing check(s)`);
      console.log('');
      console.log('失败清单:');
      for (const r of failures) {
        console.log(`  [${r.code}] ${r.item}`);
        console.log(`        ${r.actual}`);
        for (const d of r.details) {
          console.log(`        -> ${d.line ? `${d.file}:${d.line}` : d.file}  ${d.note}`);
        }
      }
    }
    if (warnings.length) {
      console.log('');
      console.log('Advisory (不判失败):');
      for (const r of warnings) {
        console.log(`  [${r.code}] ${r.item} — ${r.actual}`);
        for (const d of r.details) {
          console.log(`        -> ${d.line ? `${d.file}:${d.line}` : d.file}  ${d.note}`);
        }
      }
    }
  }

  process.exit(failures.length ? 1 : 0);
}

if (!existsSync(ROOT) || !statSync(ROOT).isDirectory()) {
  console.error(`[guard] 根目录不存在或不是目录: ${ROOT}`);
  process.exit(2);
}
if (!existsSync(join(ROOT, PLUGIN))) {
  console.error(`[guard] 根目录下找不到 ${PLUGIN}/，似乎不是 EasyTier 仓库: ${ROOT}`);
  process.exit(2);
}

runD1();
runD2();
runD3();
finish();
